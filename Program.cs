using LearnLineClient.Services;
using Microsoft.AspNetCore.ResponseCompression;

var builder = WebApplication.CreateBuilder(args);

// Configuration des services
builder.Services.AddRazorPages();
builder.Services.AddServerSideBlazor();

// Ajout du service TCP Client (Singleton pour partager la connexion)
builder.Services.AddSingleton<TcpClientService>();

// Ajout du service d'état global de l'application (Singleton)
builder.Services.AddSingleton<AppStateService>();

// Configuration de la compression des réponses pour SignalR
builder.Services.AddResponseCompression(opts =>
{
    opts.MimeTypes = ResponseCompressionDefaults.MimeTypes.Concat(
        new[] { "application/octet-stream" });
});

var app = builder.Build();

// Configuration du pipeline HTTP
if (!app.Environment.IsDevelopment())
{
    app.UseExceptionHandler("/Error");
    app.UseHsts();
}

app.UseHttpsRedirection();
app.UseStaticFiles();
app.UseRouting();

// Activation de SignalR et des composants Blazor
app.MapBlazorHub();
app.MapFallbackToPage("/_Host");

// Démarrage du serveur web
Console.WriteLine("???????????????????????????????????????????????????????????");
Console.WriteLine("    ?? LEARNLINE CLIENT - INTERFACE WEB DÉMARRÉE");
Console.WriteLine("???????????????????????????????????????????????????????????");
Console.WriteLine($"    ? URL: http://localhost:5000");
Console.WriteLine($"    ? URL HTTPS: https://localhost:5001");
Console.WriteLine("???????????????????????????????????????????????????????????");

app.Run();